import fs from 'fs'; import path from 'path';
import initSqlJs from 'sql.js';
import { initGeos } from '../src/geo.js';
import { setSqlLoader } from '../src/readers.js';
import * as E from '../src/engine.js';
await initGeos();
setSqlLoader(() => initSqlJs());
const root = new URL('../datos_prueba', import.meta.url).pathname;
const walk = (d) => fs.readdirSync(d,{withFileTypes:true}).flatMap(x => x.isDirectory()? walk(path.join(d,x.name)) : [path.join(d,x.name)]);
const entries = (sub) => walk(path.join(root, sub)).map(p => ({ path: path.relative(root, p), blob: new Blob([fs.readFileSync(p)]) }));
const iv = await E.registerFiles(entries('interv'), { group: 'interv' });
const ec = await E.registerFiles(entries('eco'), { group: 'eco' });
const cv = await E.registerFiles(entries('cov'), { group: 'cov' });
console.log(iv.layers.map(l=>[l.path,l.crsLabel,l.geometryType]), iv.errors);
console.log(ec.layers.map(l=>[l.path,l.crsLabel,l.encoding,l.fields.map(f=>f.name)]));
console.log(cv.layers.map(l=>[l.path,l.layer,l.crsLabel,l.hasSpatialIndex,l.fields.map(f=>f.name)]));
console.log(await E.sampleField(ec.layers[0].id, 'bioma_IAvH'));
const params = { interventions: iv.layers.map(l=>l.id), eco:{id:ec.layers[0].id, keyField:'bioma_IAvH', groupField:'bioma_IAvH'}, cov:{id:cv.layers[0].id, field:'cobertura'}, crs:'EPSG:9377', ellipsoid:'GRS80', residue:{threshold:0.01, action:'reasignar'} };
const r = await E.runAnalysis(params, ()=>{});
console.log('huella', r.footprint, 'seg', r.seconds);
console.log(r.ecoPieces);
console.log('partes', r.parts.length, 'total', r.parts.reduce((s,p)=>s+p.planar,0));
console.log(JSON.stringify(r.residues, null, 1));
console.log(r.warnings, r.coverage);
console.log(JSON.stringify(E.applyResidues({threshold:1, action:'reasignar'}).items.map(i=>[i.cov,i.planar,i.status,i.to,i.shared])));
const md = E.mapData(); console.log('map', md.parts.length, md.footprint.type);
const { buildTables } = await import('../src/tables.js');
const { readFactorsWorkbook, buildWorkbook } = await import('../src/excel.js');
const fx = readFactorsWorkbook(fs.readFileSync(root + '/Factores_de_Compensacion.xlsx'));
console.log(fx);
const r2 = { ...r, residues: E.applyResidues({ threshold: 1, action: 'reasignar' }) };
const cfg = { method: 'planar', factors: fx.factors, fcOverride: {}, fcCob: { 'Pastos limpios': 0.5 }, rowFcCob: {}, bioLabel: {}, ecoTemplate: '{cobertura} del {bioma}', ecoLabel: {} };
let T = buildTables(r2, cfg);
console.table(T.biomes.map(b=>({b:b.label, m2:b.m2.toFixed(2), fc:b.fc, comp:b.comp, obs:b.obs})));
console.table(T.coverages.map(b=>({b:b.label.slice(0,10), n:b.name.slice(0,40), cov:b.cov, m2:b.m2.toFixed(3), fc:b.fc, fcCob:b.fcCob, comp:b.comp})));
console.log(T.totals, T.residueArea, T.missingKeys);
T.rowKeySample = T.coverages[0].rowKey;
const cfg2 = { ...cfg, method: 'geod', fcOverride: { 'Zonobioma húmedo tropical del Meta': 6 }, rowFcCob: { [T.coverages[0].rowKey]: 2 } };
const T2 = buildTables(r2, cfg2);
console.log('geod totals', T2.totals, T2.coverages[0]);
const bytes = buildWorkbook({ tables: T2, params: { 'Método de área': 'Elipsoidal' }, warnings: [] });
fs.writeFileSync(root + '/salida_prueba.xlsx', Buffer.from(bytes));
